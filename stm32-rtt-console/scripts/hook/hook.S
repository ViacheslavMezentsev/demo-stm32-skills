@ Заглушка-перехватчик SysTick для PoC RTT: живёт в SRAM, пишет в кольцевой буфер RTT.
@
@ Идея (аналог инъекции посредника в чужой процесс на ПК): прошивка в флеше не меняется, меняется
@ только то, откуда ядро берёт обработчик — таблица векторов копируется в SRAM, её SysTick-вход
@ указывает на эту заглушку.
@
@ Что делает заглушка: на каждом тике (1 кГц) кладёт в кольцевой RTT-буфер 4 байта — маркер 'T' и
@ младшие три байта счётчика `uwTick` прошивки — и двигает WrOff. Данные появляются в канале САМИ.
@
@ Возврат — через `bx lr`: при входе в обработчик в `lr` лежит `EXC_RETURN` (0xFFFFFFF9 для
@ исключения с PSP/MSP), и `bx lr` корректно выходит из прерывания. Это надёжнее, чем переходить в
@ прежний обработчик по адресу: при переходе в флеш из SRAM-контекста мы нарушали цепочку и цель
@ падала (проверено). Цена — штатный `SysTick_Handler` не вызывается; для PoC это допустимо и
@ записано в ограничениях.
@
@ Адреса и константы задаются при ассемблировании через --defsym:
@   RTT_CB, RTT_WROFF (смещение в блоке), RTT_BUF, RTT_SIZE, TICK_VAR

    .syntax unified
    .cpu cortex-m4
    .thumb

    .section .text
    .global rtt_systick_hook
    .type rtt_systick_hook, %function
rtt_systick_hook:
    @ Сохраняем всё, что можем испортить: заглушка обязана быть прозрачной для прерванного кода.
    push    {r0-r3, r12, lr}

    @ --- запись в кольцевой буфер RTT ---
    ldr     r0, =RTT_CB
    ldr     r2, [r0, #RTT_WROFF]

    ldr     r1, =RTT_BUF
    add     r1, r1, r2

    @ Байт 0: маркер 'T' = 0x54
    movs    r3, #0x54
    strb    r3, [r1, #0]

    @ Байты 1..3: младшие три байта счётчика тиков прошивки.
    ldr     r3, =TICK_VAR
    ldr     r3, [r3]
    strb    r3, [r1, #1]
    lsrs    r3, r3, #8
    strb    r3, [r1, #2]
    lsrs    r3, r3, #8
    strb    r3, [r1, #3]

    @ WrOff += 4, при переполнении — сброс на 0.
    adds    r2, r2, #4
    cmp     r2, #RTT_SIZE
    blt     1f
    movs    r2, #0
1:
    ldr     r0, =RTT_CB
    str     r2, [r0, #RTT_WROFF]

    @ Выход из прерывания: восстанавливаем контекст (включая EXC_RETURN в lr) и делаем bx lr.
    pop     {r0-r3, r12, lr}
    bx      lr

    .ltorg
