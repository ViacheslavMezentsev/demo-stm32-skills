@ Заглушка перехвата ВОЗВРАТА: получает управление, когда функция вернулась, и видит её результат.
@
@ Идея. Функция возвращает управление по адресу из `lr` (при прологе `push {..., lr}` адрес лежит на
@ стеке, а `pop {..., pc}` прыгает по нему). Если перед вызовом подменить `lr` на эту заглушку, то
@ функция отработает как обычно и вернёт управление НАМ — причём в `r0` уже будет её возвращаемое
@ значение. Заглушка записывает его в RTT и уходит по исходному адресу возврата, поэтому вызывающий код
@ ничего не замечает.
@
@ Зачем это нужно. Ни перехват вектора, ни аппаратная точка останова не дают **результат** функции:
@ первая видит только момент прерывания, вторая — аргументы на входе. Здесь мы получаем именно
@ возвращаемое значение.
@
@ Цена. Подмену делает отладчик (одна остановка на вызов), поэтому метод медленный, как и точки
@ останова: только для редких вызовов.
@
@ Регистры. В момент входа в заглушку функция уже вернула стек в состояние вызывающего. Мы обязаны
@ сохранить r4 (по ABI его сохраняет вызываемый) и вернуть r0 без изменений — это результат.
@
@ --defsym: RTT_CB, RTT_WROFF, RTT_BUF, RTT_SIZE, TICK_VAR, RETURN_TO (ячейка с исходным адресом возврата)

    .syntax unified
    .cpu cortex-m4
    .thumb

    .section .text
    .global retval_hook
    .type retval_hook, %function
retval_hook:
    push    {r4, lr}
    @ Возвращаемое значение — в r4, пока пишем кадр.
    mov     r4, r0

    ldr     r0, =RTT_CB
    ldr     r2, [r0, #RTT_WROFF]
    ldr     r1, =RTT_BUF
    add     r1, r1, r2

    @ Байт 0: маркер 'R' (Return)
    movs    r3, #0x52
    strb    r3, [r1, #0]

    @ Байты 1..4: возвращаемое значение как есть (для float это его биты)
    strb    r4, [r1, #1]
    lsrs    r3, r4, #8
    strb    r3, [r1, #2]
    lsrs    r3, r4, #16
    strb    r3, [r1, #3]
    lsrs    r3, r4, #24
    strb    r3, [r1, #4]

    @ Байты 5..7: младшие три байта тика — видно, когда именно был вызов
    ldr     r3, =TICK_VAR
    ldr     r3, [r3]
    strb    r3, [r1, #5]
    lsrs    r3, r3, #8
    strb    r3, [r1, #6]
    lsrs    r3, r3, #8
    strb    r3, [r1, #7]

    @ WrOff += 8 с кольцевым переходом
    adds    r2, r2, #8
    cmp     r2, #RTT_SIZE
    blt     1f
    movs    r2, #0
1:
    ldr     r0, =RTT_CB
    str     r2, [r0, #RTT_WROFF]

    @ Возвращаем r0 (результат) и уходим по исходному адресу возврата.
    @ Адрес держим в r12 (scratch): r4 и lr восстанавливаются из стека, r12 — нет,
    @ поэтому загружать его надо ПОСЛЕ подготовки к pop и не брать r4-r11 (их pop затрёт).
    mov     r0, r4
    ldr     r12, =RETURN_TO
    ldr     r12, [r12]
    pop     {r4, lr}
    bx      r12

    .ltorg
