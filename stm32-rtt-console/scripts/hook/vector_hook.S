@ Прозрачная заглушка-перехватчик обработчика исключения: пишет в RTT и вызывает ШТАТНЫЙ обработчик.
@
@ Отличие от первой версии (hook.S): та выходила из прерывания через `bx lr` и не вызывала прежний
@ обработчик, из-за чего `HAL_IncTick` не выполнялся и `HAL_Delay` ломался. Здесь в конце вызывается
@ оригинальный обработчик через `blx`, поэтому поведение прошивки полностью сохраняется: перехват
@ становится наблюдателем, а не заменой.
@
@ Как сохраняется EXC_RETURN: при входе в исключение в `lr` лежит значение возврата (0xFFFFFFF9 и т.п.).
@ Вызов `blx` затрёт `lr`, поэтому EXC_RETURN сохраняется на стек и восстанавливается после вызова.
@ Оригинальный обработчик обязан сохранять r4-r11 (соглашение ABI), поэтому наши r4/r5 не портятся
@ вызываемым кодом — но на всякий случай сохраняем и их.
@
@ --defsym: RTT_CB, RTT_WROFF, RTT_BUF, RTT_SIZE, TICK_VAR, ORIG_HANDLER (адрес с битом Thumb)

    .syntax unified
    .cpu cortex-m4
    .thumb

    .section .text
    .global vector_hook
    .type vector_hook, %function
vector_hook:
    @ Порядок важен: сначала сохраняем контекст вместе с EXC_RETURN (он в lr).
    push    {r0-r3, r12, lr}
    @ r4/r5 используем как рабочие — сохраняем их тоже (мы внутри обработчика, ABI не обязывает,
    @ но прерванный код ожидает их неизменными после выхода из прерывания).
    push    {r4, r5}

    @ --- запись кадра в кольцевой буфер RTT ---
    ldr     r0, =RTT_CB
    ldr     r2, [r0, #RTT_WROFF]

    ldr     r1, =RTT_BUF
    add     r1, r1, r2

    @ Байт 0: маркер 'S' (Sample)
    movs    r3, #0x53
    strb    r3, [r1, #0]

    @ Байты 1..3: младшие три байта счётчика тиков прошивки
    ldr     r3, =TICK_VAR
    ldr     r3, [r3]
    strb    r3, [r1, #1]
    lsrs    r3, r3, #8
    strb    r3, [r1, #2]
    lsrs    r3, r3, #8
    strb    r3, [r1, #3]

    @ WrOff += 4 с кольцевым переходом
    adds    r2, r2, #4
    cmp     r2, #RTT_SIZE
    blt     1f
    movs    r2, #0
1:
    ldr     r0, =RTT_CB
    str     r2, [r0, #RTT_WROFF]

    @ --- вызов штатного обработчика ---
    @ `blx` затрёт lr, но EXC_RETURN уже лежит на стеке (первый push).
    ldr     r0, =ORIG_HANDLER
    blx     r0

    @ --- выход из прерывания ---
    pop     {r4, r5}
    pop     {r0-r3, r12, lr}        @ здесь восстанавливается EXC_RETURN
    bx      lr

    .ltorg
