@ Нативная заглушка: работает по прерыванию СВОБОДНОГО таймера (TIM2), без участия отладчика.
@
@ Зачем. Все методы с остановками (точка останова, перехват возврата) стоят ~1 с на событие, потому что
@ каждое событие обслуживает хост. Нативное решение выполняется на самой цели с полной скоростью.
@
@ VTOR даёт нативное исполнение только для уже работающих векторов (SysTick 1 кГц, и его трогать
@ нежелательно: это часы HAL). Здесь используется **свободный таймер**: прошивка TIM2 не использует
@ (проверено: 0 упоминаний), поэтому его прерывание можно направить на нашу заглушку через копию
@ таблицы векторов в SRAM (`VTOR`), а частоту задать любую — от единиц герц до десятков килогерц.
@
@ Прошивка об этом не знает: она не включает TIM2, не настраивает его и не занимает его вектор.
@ Флеш не меняется; после сброса всё исчезает.
@
@ Что делает заглушка: сбрасывает флаг прерывания таймера (иначе прерывание будет повторяться
@ бесконечно) и пишет в кольцевой буфер RTT кадр из 4 байт: маркер 'M' и три младших байта `uwTick`.
@ Метка тика позволяет измерить фактическую частоту по часам самой прошивки.
@
@ --defsym: RTT_CB, RTT_WROFF, RTT_BUF, RTT_SIZE, TICK_VAR, TIM_SR (адрес регистра состояния TIM2)

    .syntax unified
    .cpu cortex-m4
    .thumb

    .section .text
    .global timer_hook
    .type timer_hook, %function
timer_hook:
    push    {r0-r3, r12, lr}

    @ Счётчик прерываний в RAM: нужен, потому что на высокой частоте кольцевой буфер перезаписывается
    @ и считать кадры нельзя — а счётчик фиксирует КАЖДОЕ прерывание.
    ldr     r0, =COUNTER
    ldr     r1, [r0]
    @ Тик первого прерывания: запоминаем один раз, чтобы измерить окно по часам прошивки.
    @ Своя метка нужна потому, что после reset содержимое RAM сохраняется и внешнее «тик до» может быть
    @ устаревшим (uwTick обнулится только когда прошивка выполнит очистку .bss).
    cmp     r1, #0
    bne     2f
    ldr     r2, =TICK_VAR
    ldr     r2, [r2]
    ldr     r3, =FIRST_TICK
    str     r2, [r3]
2:
    adds    r1, r1, #1
    str     r1, [r0]

    @ Тик последнего прерывания — вторая граница окна.
    ldr     r2, =TICK_VAR
    ldr     r2, [r2]
    ldr     r3, =LAST_TICK
    str     r2, [r3]

    @ Сброс флага прерывания: у таймеров STM32 флаги очищаются записью нуля (rc_w0).
    ldr     r0, =TIM_SR
    movs    r1, #0
    str     r1, [r0]

    @ --- запись кадра в RTT ---
    ldr     r0, =RTT_CB
    ldr     r2, [r0, #RTT_WROFF]
    ldr     r1, =RTT_BUF
    add     r1, r1, r2

    @ Байт 0: маркер 'M' (Timer)
    movs    r3, #0x4D
    strb    r3, [r1, #0]

    @ Байты 1..3: младшие три байта тика прошивки
    ldr     r3, =TICK_VAR
    ldr     r3, [r3]
    strb    r3, [r1, #1]
    lsrs    r3, r3, #8
    strb    r3, [r1, #2]
    lsrs    r3, r3, #8
    strb    r3, [r1, #3]

    @ WrOff += 4 с кольцевым переходом
    adds    r2, r2, #4
    cmp     r2, #RTT_SIZE
    blt     1f
    movs    r2, #0
1:
    ldr     r0, =RTT_CB
    str     r2, [r0, #RTT_WROFF]

    pop     {r0-r3, r12, lr}
    bx      lr

    .ltorg
